-- ============================================================================
-- REFERENCE DIMENSIONS (must exist before arrivals/ingestion)
-- ============================================================================

-- Routes: CTA route identifiers and names
-- Primary key: route_id (text, e.g., "Red", "Blue")
-- Application: Loaded from routes before arrival insertion
CREATE TABLE IF NOT EXISTS routes (
    route_id TEXT PRIMARY KEY,
    route_name TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_routes_name ON routes(route_name);

-- Destinations: Stop names and destinations
-- Programmatic allocation: Application uses MAX(destination_id) + exclusive lock
-- No natural key; destination_id must be allocated by application
CREATE TABLE IF NOT EXISTS destinations (
    destination_id INTEGER PRIMARY KEY,
    destination_name TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_destinations_name ON destinations(destination_name);

-- ============================================================================
-- INGESTION AND ARRIVAL TRACKING
-- ============================================================================

-- ingestion_files: Registry of downloaded CTA XML snapshots
--
-- Key design decisions:
-- - file_id: BIGSERIAL (auto-generated by database), used for FK to arrivals
-- - source_file: TEXT UNIQUE, the actual S3/bucket object key
-- - file_generated_timestamp: When the CTA snapshot was created (Chicago time → UTC)
-- - station_id: Normalized integer station ID
-- - status: Processing state: pending → processing → processed (or failed)
-- - row_count: Number of arrival records extracted from this file (can be 0)
-- - attempts: Incremented each time status = 'failed'
-- - last_error: Error message from most recent failure attempt
-- - processed_at: Set to NOW() when status changes to 'processed'
-- - created_at, updated_at: Lifecycle timestamps
--
CREATE TABLE IF NOT EXISTS ingestion_files (
    file_id BIGSERIAL PRIMARY KEY,
    source_file TEXT NOT NULL UNIQUE,
    file_generated_timestamp TIMESTAMPTZ,
    station_id INTEGER NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('pending', 'processing', 'processed', 'failed')),
    row_count INTEGER NOT NULL DEFAULT 0,
    attempts INTEGER NOT NULL DEFAULT 0,
    last_error TEXT,
    processed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_ingestion_files_status ON ingestion_files(status);
CREATE INDEX IF NOT EXISTS idx_ingestion_files_station_id ON ingestion_files(station_id);
CREATE INDEX IF NOT EXISTS idx_ingestion_files_file_generated_timestamp ON ingestion_files(file_generated_timestamp DESC NULLS LAST);
CREATE INDEX IF NOT EXISTS idx_ingestion_files_updated_at ON ingestion_files(updated_at DESC);

-- arrivals: Parsed arrival predictions from CTA XML snapshots
--
-- Key design decisions:
-- - arrival_id: BIGSERIAL, only for internal reference
-- - file_id: FK to ingestion_files (BIGINT from BIGSERIAL)
-- - UNIQUE constraint: (file_id, stop_id, route_id, arrival_time, run_number)
--   - Defines uniqueness of an arrival record within a file
-- - ON CONFLICT DO UPDATE: Only updates boolean prediction flags if they differ
-- - collection_timestamp: ALWAYS NOW() - the database insertion time (UTC)
--   - NOT the CTA snapshot time (that's file_generated_timestamp in ingestion_files)
-- - All boolean fields nullable: CTA may not provide all predictions
--
CREATE TABLE IF NOT EXISTS arrivals (
    arrival_id BIGSERIAL PRIMARY KEY,
    file_id BIGINT NOT NULL REFERENCES ingestion_files(file_id) ON DELETE CASCADE,
    station_id INTEGER NOT NULL,
    stop_id TEXT NOT NULL,
    route_id TEXT NOT NULL REFERENCES routes(route_id),
    destination_id INTEGER REFERENCES destinations(destination_id),
    direction TEXT,
    prediction_time TIMESTAMPTZ,
    arrival_time TIMESTAMPTZ NOT NULL,
    is_approaching BOOLEAN,
    is_delayed BOOLEAN,
    is_scheduled BOOLEAN,
    is_fault BOOLEAN,
    latitude NUMERIC(10,6),
    longitude NUMERIC(10,6),
    heading INTEGER,
    wait_time NUMERIC(10,2),
    run_number TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    inserted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    collection_timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (file_id, stop_id, route_id, arrival_time, run_number)
);

CREATE INDEX IF NOT EXISTS idx_arrivals_file_id ON arrivals(file_id);
CREATE INDEX IF NOT EXISTS idx_arrivals_station_id ON arrivals(station_id);
CREATE INDEX IF NOT EXISTS idx_arrivals_arrival_time ON arrivals(arrival_time DESC);
CREATE INDEX IF NOT EXISTS idx_arrivals_inserted_at ON arrivals(inserted_at DESC);

-- ============================================================================
-- COLLECTION LEDGER
-- ============================================================================

-- collection_runs: Tracks each collection cycle
--
-- Key design decisions:
-- - run_id: UUID primary key (generated by application)
-- - Collection cycles are 5-minute intervals
-- - status lifecycle: running → completed/partial/failed
-- - expected_station_count: Total stations configured for collection
-- - deployment_commit: git SHA (RAILWAY_GIT_COMMIT_SHA) to track which version ran
--
CREATE TABLE IF NOT EXISTS collection_runs (
    run_id UUID PRIMARY KEY,
    status TEXT NOT NULL CHECK (status IN ('running', 'completed', 'partial', 'failed')),
    expected_station_count INTEGER NOT NULL,
    deployment_commit TEXT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    uploaded_station_count INTEGER DEFAULT 0,
    failed_station_count INTEGER DEFAULT 0,
    fatal_error_type TEXT
);

CREATE INDEX IF NOT EXISTS idx_collection_runs_status ON collection_runs(status);
CREATE INDEX IF NOT EXISTS idx_collection_runs_started_at ON collection_runs(started_at DESC);

-- collection_attempts: Per-station outcomes within each collection run
--
-- Key design decisions:
-- - Composite key: (run_id, station_id) - one row per station per run
-- - status lifecycle: pending → in_progress → (uploaded/failed/not_attempted)
-- - stage: Detailed processing step (cta_request, xml_parse, upload, complete, etc.)
-- - request_attempts: HTTP request retry counter
-- - http_status, cta_error_code: CTA response codes
-- - error_type: Application categorization
-- - storage_error_code, storage_http_status: S3/bucket failure details
-- - source_file: Downloaded XML filename (NULL if fetch failed)
-- - object_key: Bucket path where XML was archived (NULL if upload failed)
-- - last_retry_http_status, last_retry_error_type: Optional retry history
--
CREATE TABLE IF NOT EXISTS collection_attempts (
    run_id UUID NOT NULL REFERENCES collection_runs(run_id) ON DELETE CASCADE,
    station_id INTEGER NOT NULL,
    station_name TEXT NOT NULL,
    station_index INTEGER NOT NULL,
    status TEXT NOT NULL CHECK (
        status IN ('pending', 'in_progress', 'uploaded', 'failed', 'not_attempted')
    ),
    stage TEXT,
    request_attempts INTEGER DEFAULT 0,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    http_status INTEGER,
    cta_error_code TEXT,
    error_type TEXT,
    storage_error_code TEXT,
    storage_http_status INTEGER,
    source_file TEXT,
    object_key TEXT,
    duration_seconds NUMERIC(10,2),
    last_retry_http_status INTEGER,
    last_retry_error_type TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (run_id, station_id)
);

CREATE INDEX IF NOT EXISTS idx_collection_attempts_status ON collection_attempts(status);
CREATE INDEX IF NOT EXISTS idx_collection_attempts_created_at ON collection_attempts(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_collection_attempts_run_id ON collection_attempts(run_id);

-- ============================================================================
-- PENDING UPLOADS (failure recovery)
-- ============================================================================

-- pending_uploads: Validated XML deferred for archival when bucket is unavailable
--
-- Key design decisions:
-- - Acts as a temporary queue for XML uploads that failed due to bucket unavailability
-- - source_file is PRIMARY KEY (unique, one row per file)
-- - Bounded capacity: Application enforces MAX_ROWS (default 40000)
-- - Rows deleted after successful archival verification (checksum match)
-- - xml_gzip: Compressed bytes of original CTA XML response
-- - sha256: Checksum for verification during archival
--
CREATE TABLE IF NOT EXISTS pending_uploads (
    source_file TEXT PRIMARY KEY,
    object_key TEXT NOT NULL,
    xml_gzip BYTEA NOT NULL,
    sha256 TEXT NOT NULL,
    run_id UUID REFERENCES collection_runs(run_id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_pending_uploads_created_at ON pending_uploads(created_at);
CREATE INDEX IF NOT EXISTS idx_pending_uploads_run_id ON pending_uploads(run_id);

-- ============================================================================
-- QUALITY AUDIT AND RECOVERY
-- ============================================================================

-- arrival_resolution_audit: Immutable record of arrival disambiguation
--
-- Purpose:
-- 1. Preserve source evidence (original XML, its hash, bucket reference)
-- 2. Record disambiguation decisions made during ingestion
-- 3. Enable deterministic replay and audit verification
-- 4. Support recovery: Re-parse archived XML using same policy
--
-- Key design decisions:
-- - file_id: FK to ingestion_files (BIGINT)
-- - policy: Versioned policy identifier used for disambiguation
-- - source_sha256: SHA256 of original XML response
-- - source_etag: Optional S3/bucket ETag
-- - source_xml_gzip: Compressed original CTA XML (immutable evidence)
-- - evidence: JSONB decision log
-- - canonical_row_count: Number of final arrival rows after disambiguation
--
CREATE TABLE IF NOT EXISTS arrival_resolution_audit (
    file_id BIGINT PRIMARY KEY REFERENCES ingestion_files(file_id) ON DELETE CASCADE,
    policy TEXT NOT NULL,
    source_sha256 TEXT NOT NULL,
    source_etag TEXT,
    source_xml_gzip BYTEA,
    evidence JSONB,
    canonical_row_count INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_arrival_resolution_audit_created_at ON arrival_resolution_audit(created_at DESC);

-- ============================================================================
-- MONITORING AND ALERTING
-- ============================================================================

-- monitoring_alert_state: Track alert deduplication by state_key
--
-- Used by health_check.py to track alert status and prevent duplicate notifications
-- - state_key: Unique identifier for an alert state (e.g., "station_stale_18th")
-- - issue_signature: Hash/signature of the issue for change detection
-- - checked_at: Last time this state was checked
-- - last_email_at: Last time an email alert was sent
--
CREATE TABLE IF NOT EXISTS monitoring_alert_state (
    state_key TEXT PRIMARY KEY,
    issue_signature TEXT NOT NULL DEFAULT '',
    checked_at TIMESTAMPTZ,
    last_email_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_monitoring_alert_state_key ON monitoring_alert_state(state_key);

